#include <iostream>
using namespace std;

int main() {

    // Constants
    int a = 10;          // 10 is an integer constant
    int b = 5;           // 5 is an integer constant
    char ch = 'A';       // 'A' is a character constant

    // String
    cout << "Welcome to C++ Programming\n";

    // Operators
    int sum = a + b;     // '+' is an operator
    int diff = a - b;    // '-' is an operator

    // Displaying values
    cout << "Sum = " << sum << endl;
    cout << "Difference = " << diff << endl;
    cout << "Character = " << ch << endl;

    // Punctuators used:
    // ;  -> end of statement
    // {} -> block of code
    // () -> function

    return 0;
}
