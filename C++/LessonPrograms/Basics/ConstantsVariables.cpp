#include <iostream>
using namespace std;

int main() {

    // Constant (value cannot be changed)
    const float PI = 3.14;

    // Variables (values can change)
    int days = 7;
    int age = 23;
    float height = 5.9;
    char grade = 'A';

    // Displaying constant value
    cout << "PI = " << PI << endl;

    // Displaying variable values
    cout << "Days in a week = " << days << endl;
    cout << "Age = " << age << endl;
    cout << "Height = " << height << endl;
    cout << "Grade = " << grade << endl;

    return 0;
}
