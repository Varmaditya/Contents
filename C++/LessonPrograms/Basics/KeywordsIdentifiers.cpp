#include <iostream>
using namespace std;

int main() {

    // int, float, char are keywords
    // age, height, grade are identifiers

    int age = 23;          // 'int' is a keyword, 'age' is an identifier
    float height = 5.9;    // 'float' is a keyword, 'height' is an identifier
    char grade = 'A';      // 'char' is a keyword, 'grade' is an identifier

    // cout and endl are part of standard library (used for output)

    cout << "Age: " << age << endl;
    cout << "Height: " << height << endl;
    cout << "Grade: " << grade << endl;

    // return is a keyword
    return 0;
}
