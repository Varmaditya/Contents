#include <iostream>
#include <string>
using namespace std;

int main() {

    // Declaring strings
    string firstName;
    string lastName;

    // Initializing strings
    firstName = "John";
    lastName = "Doe";

    // Displaying strings
    cout << "First Name: " << firstName << endl;
    cout << "Last Name: " << lastName << endl;

    // Direct initialization
    string course = "C++ Programming";

    cout << "Course: " << course << endl;

    return 0;
}