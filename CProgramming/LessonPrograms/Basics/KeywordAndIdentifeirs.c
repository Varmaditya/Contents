#include <stdio.h>   // include → keyword, stdio.h → header file

int main() {   // int → keyword, main → identifier

    int age = 23;            // int → keyword, age → identifier
    float height = 5.9;      // float → keyword, height → identifier
    char grade = 'A';        // char → keyword, grade → identifier

    printf("Age: %d\n", age);       // printf → identifier
    printf("Height: %.1f\n", height);
    printf("Grade: %c\n", grade);

    return 0;   // return → keyword

}
